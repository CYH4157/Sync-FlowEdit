def main():
    pans = []
    for group, items in [("indoor", INDOOR), ("outdoor", OUTDOOR)]:
        for aid, src, edits in items:
            pans.append({"image": f"{aid}.jpg", "group": group, "src": P + src,
                         "edits": [{"name": n, "tar": P + t} for n, t in edits]})
    out = os.path.join(os.path.dirname(__file__), "..", "configs", "edits.yaml")
    with open(out, "w", encoding="utf-8") as f:
        f.write("# generated by scripts/make_edits.py\n")
        yaml.safe_dump({"root": "data/pano", "panoramas": pans}, f, allow_unicode=True, sort_keys=False, width=200)
    n = sum(len(p["edits"]) for p in pans)
    print(f"{len(pans)} panoramas, {n} edits -> {out}")


if __name__ == "__main__":
    main()
